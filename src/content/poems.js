/** id → Poem 조회용 인덱스 */
export const POEM_BY_ID = new Map(POEMS.map((p) => [p.id, p]));

/** 시 본문을 한 덩어리 문자열로 만든다. */
export function poemText(poem) {
  return poem.stanzas.map((st) => st.join('\n')).join('\n\n');
}

/** 시의 모든 행을 평평하게 편다. */
export function poemLines(poem) {
  return poem.stanzas.flat();
}

/** 시 미리보기(첫 연의 앞 두 행). */
export function poemPreview(poem) {
  const lines = poemLines(poem);
  const head = lines.slice(0, poem.form === 'prose' ? 1 : 2).join(' / ');
  return head.length > 80 ? head.slice(0, 79) + '…' : head;
}
